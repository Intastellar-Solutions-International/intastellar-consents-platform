/**
 * GET/POST /api/cron-ad-click-resolve
 *
 * Vercel cron — resolves gclids captured by our own tracking script to the
 * real Google Ads campaign/ad group that produced them, via the click_view
 * resource (see fetchGoogleAdsClicksByGclid in _ad-platform-fetch.js).
 *
 * Why this exists: utm_campaign is a string the advertiser chose to put in a
 * tracking template — it can be a human name, a raw numeric ID, an
 * unsubstituted ValueTrack placeholder ("{campaignid}"), or simply absent
 * (Google's default auto-tagging only appends gclid, not utm_* params, unless
 * the advertiser also configured manual UTM tracking). A gclid, by contrast,
 * is generated by Google Ads itself at click time, so resolving it is a
 * lookup against the platform's own record of the click, not a guess.
 *
 * Only google_ads is implemented. Microsoft Advertising and Meta have no
 * equivalent public *read* API to decode msclkid/fbclid back to a campaign —
 * their click IDs are consumed write-only, for offline conversion import
 * (see ad-conversion-push.js), where the platform does its own internal
 * attribution. That's a real gap, not an oversight; see the comment on
 * fetchGoogleAdsClicksByGclid for details.
 *
 * For every active google_ads connection:
 *   1. Looks up the connection's site_id (organisation_id + domain).
 *   2. Finds distinct gclids seen in analytics_events within the lookback
 *      window that either have no resolution row yet, or have a "not found"
 *      row old enough to deserve one more retry (click_view data can lag a
 *      few hours behind the click).
 *   3. Groups those gclids by the calendar day they were captured (click_view
 *      requires a single-day segments.date filter) and resolves each day's
 *      gclids in batches via fetchGoogleAdsClicksByGclid.
 *   4. Upserts every attempted gclid into analytics_click_resolutions —
 *      found ones with the resolved campaign/ad group, not-found ones just
 *      so they're not retried again until the next lookback window passes
 *      (bounding API usage instead of retrying forever).
 *
 * Two auth modes (mirrors cron-ad-sync.js):
 *   1. Vercel cron: Authorization: Bearer <CRON_SECRET>  — sweeps every org.
 *   2. Manual trigger from the dashboard: Authorization: Bearer <JWT> +
 *      Organisation header + optional ?domain= — scoped to the caller's org.
 *
 * Required env vars:
 *   CRON_SECRET, POSTGRES_URL, GOOGLE_ADS_DEVELOPER_TOKEN,
 *   GOOGLE_CLIENT_ID / GOOGLE_CLIENT_SECRET (token refresh)
 *
 * Optional env vars:
 *   CRON_AD_CLICK_RESOLVE_LOOKBACK_DAYS — how far back to look for unresolved
 *                                          gclids (default 3, cap 90 — the
 *                                          outer edge of click_view's window)
 *   CRON_AD_CLICK_RESOLVE_BATCH_SIZE    — gclids per click_view query
 *                                          (default 50)
 */

import { tryRefreshToken, fetchGoogleAdsClicksByGclid } from "./_ad-platform-fetch.js";
import { getPool } from "./_db.js";
import { validateJwt, withMembership } from "./_member-auth.js";

const LOOKBACK_DAYS = Math.min(parseInt(process.env.CRON_AD_CLICK_RESOLVE_LOOKBACK_DAYS || "3", 10), 90);
const BATCH_SIZE     = Math.min(parseInt(process.env.CRON_AD_CLICK_RESOLVE_BATCH_SIZE    || "50", 10), 200);

async function ensureResolutionsTable(db) {
    await db.query(`
        CREATE TABLE IF NOT EXISTS analytics_click_resolutions (
            id              BIGSERIAL    PRIMARY KEY,
            organisation_id INTEGER      NOT NULL,
            domain          TEXT         NOT NULL,
            platform        TEXT         NOT NULL,
            click_id        TEXT         NOT NULL,
            click_date      DATE         NOT NULL,
            found           BOOLEAN      NOT NULL DEFAULT false,
            campaign_id     TEXT,
            campaign_name   TEXT,
            ad_group_id     TEXT,
            ad_group_name   TEXT,
            resolved_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
            UNIQUE (organisation_id, domain, platform, click_id)
        )
    `);
    await db.query(`CREATE INDEX IF NOT EXISTS analytics_click_resolutions_lookup
                     ON analytics_click_resolutions (organisation_id, domain, platform, click_id)`);
}

function isoDate(d) {
    return d.toISOString().slice(0, 10);
}

async function handler(req, res) {
    if (req.method !== "GET" && req.method !== "POST") {
        return res.status(405).json({ error: "Method not allowed" });
    }

    const secret = process.env.CRON_SECRET;
    const isCronCall = secret && req.headers.authorization === `Bearer ${secret}`;
    const jwt = !isCronCall ? validateJwt(req.headers.authorization) : null;

    if (!isCronCall && !jwt) {
        return res.status(401).json({ error: "Unauthorized" });
    }

    const db = getPool();
    await ensureResolutionsTable(db);

    const manualOrgId  = jwt ? parseInt(req.headers.organisation || "", 10) : null;
    const manualDomain = jwt ? (req.query.domain || "").trim().toLowerCase() : null;

    const whereExtra = manualOrgId
        ? `AND organisation_id = ${manualOrgId}
           ${manualDomain ? `AND LOWER(domain) = '${manualDomain.replace(/'/g, "''")}'` : ""}`
        : "";

    const { rows: connections } = await db.query(`
        SELECT organisation_id, domain, platform, account_id, account_label,
               login_customer_id, account_currency, access_token, refresh_token, token_expires_at
        FROM ad_platform_connections
        WHERE platform = 'google_ads' AND account_id IS NOT NULL AND access_token IS NOT NULL
        ${whereExtra}
        ORDER BY organisation_id, domain
    `);

    const windowStart = `NOW() - INTERVAL '${LOOKBACK_DAYS} days'`;
    const retryAfter   = `NOW() - INTERVAL '20 hours'`;

    const results = [];
    let totalResolved = 0;
    let totalAttempted = 0;

    for (const rawConn of connections) {
        const conn = { ...rawConn };
        const tag = `[google_ads] ${conn.domain}`;

        const { rows: siteRows } = await db.query(
            `SELECT id FROM analytics_sites WHERE organisation_id = $1 AND LOWER(domain) = LOWER($2) AND active = true LIMIT 1`,
            [conn.organisation_id, conn.domain]
        );
        if (!siteRows.length) {
            results.push({ tag, status: "skipped", reason: "no analytics site for this domain" });
            continue;
        }
        const siteId = siteRows[0].id;

        try {
            const refreshed = await tryRefreshToken(db, conn);
            conn.access_token = refreshed.access_token;
        } catch (e) {
            console.warn(`${tag} token refresh failed:`, e.message);
        }

        // Distinct gclids seen in the lookback window that either have no
        // resolution row yet, or have a stale "not found" row worth one more
        // retry (click_view can lag the click by a few hours).
        const { rows: pending } = await db.query(
            `SELECT DISTINCT e.gclid AS click_id, (e.received_at AT TIME ZONE 'UTC')::date AS click_date
             FROM analytics_events e
             LEFT JOIN analytics_click_resolutions r
               ON r.organisation_id = $1 AND r.domain = $2 AND r.platform = 'google_ads' AND r.click_id = e.gclid
             WHERE e.site_id = $3
               AND e.gclid IS NOT NULL AND e.gclid != ''
               AND e.received_at >= ${windowStart}
               AND (r.click_id IS NULL OR (r.found = false AND r.resolved_at < ${retryAfter}))`,
            [conn.organisation_id, conn.domain, siteId]
        ).catch((err) => {
            if (err?.message?.includes("does not exist")) return { rows: [] };
            throw err;
        });

        if (!pending.length) {
            results.push({ tag, status: "up-to-date" });
            continue;
        }

        // click_view needs a single-day segments.date filter — group pending
        // gclids by day, then batch each day's list to keep query size sane.
        const byDay = new Map();
        for (const row of pending) {
            const day = row.click_date instanceof Date ? isoDate(row.click_date) : String(row.click_date);
            if (!byDay.has(day)) byDay.set(day, []);
            byDay.get(day).push(row.click_id);
        }

        let resolvedCount = 0;
        let attemptedCount = 0;
        let lastError = null;

        for (const [day, gclidsForDay] of byDay) {
            for (let i = 0; i < gclidsForDay.length; i += BATCH_SIZE) {
                const batch = gclidsForDay.slice(i, i + BATCH_SIZE);
                let found;
                try {
                    found = await fetchGoogleAdsClicksByGclid(conn, batch, day);
                } catch (e) {
                    console.error(`${tag} click_view fetch failed for ${day}:`, e.message);
                    lastError = e.message;
                    continue;
                }
                for (const gclid of batch) {
                    attemptedCount++;
                    const match = found.get(gclid) || null;
                    if (match) resolvedCount++;
                    await db.query(
                        `INSERT INTO analytics_click_resolutions
                            (organisation_id, domain, platform, click_id, click_date, found,
                             campaign_id, campaign_name, ad_group_id, ad_group_name, resolved_at)
                         VALUES ($1,$2,'google_ads',$3,$4::date,$5,$6,$7,$8,$9,NOW())
                         ON CONFLICT (organisation_id, domain, platform, click_id) DO UPDATE SET
                            found         = EXCLUDED.found,
                            campaign_id   = EXCLUDED.campaign_id,
                            campaign_name = EXCLUDED.campaign_name,
                            ad_group_id   = EXCLUDED.ad_group_id,
                            ad_group_name = EXCLUDED.ad_group_name,
                            resolved_at   = NOW()`,
                        [
                            conn.organisation_id, conn.domain, gclid, day, !!match,
                            match?.campaignId ?? null, match?.campaignName ?? null,
                            match?.adGroupId ?? null, match?.adGroupName ?? null,
                        ]
                    ).catch((e) => console.error(`${tag} upsert failed for gclid ${gclid}:`, e.message));
                }
            }
        }

        totalResolved += resolvedCount;
        totalAttempted += attemptedCount;
        results.push({
            tag, status: lastError ? "partial-error" : "resolved",
            attempted: attemptedCount, resolved: resolvedCount,
            ...(lastError ? { error: lastError } : {}),
        });
        console.log(`${tag} resolved ${resolvedCount}/${attemptedCount} gclids`);
    }

    return res.status(200).json({
        ok: true,
        connections: connections.length,
        totalAttempted,
        totalResolved,
        results,
    });
}

export default withMembership(handler);
